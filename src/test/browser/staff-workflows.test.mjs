test('UI3: Navigation abbrechen erhält ungesendeten Mitarbeitertext', async t => {
    const { page, context } = await fixture(t);
    await createCase(page, context);
    const url = page.url();
    await page.locator('#message').click();
    await page.locator('#message').fill('Nicht verlieren');
    let warnings = 0;
    page.on('dialog', async dialog => { warnings++; assert.equal(dialog.type(), 'beforeunload'); await dialog.dismiss(); });
    await page.getByRole('link', { name: 'Zur Fallübersicht' }).click({ noWaitAfter: true });
    await until(() => warnings === 1);
    assert.equal(page.url(), url);
    assert.equal(await page.locator('#message').inputValue(), 'Nicht verlieren');
});
