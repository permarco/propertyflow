test('UI3: Polling meldet Änderungen, erhält laufenden Stream und sperrt bei Abschluss', async t => {
    const { page, context } = await fixture(t);
    await freeze(page);
    const c = await createCase(page, context);
    await page.clock.runFor(19000);
    await page.locator('#message').fill('Laufender Entwurf');
    await page.locator('#generate').click();
    await publish(context, c, 'Neue Mieternachricht', false, true);
    await change(context, c, 'urgency', 'Hoch');
    await page.clock.runFor(1000);
    await until(async () => await page.locator('#updates').isVisible());
    assert.match(await page.locator('#update-text').textContent(), /Noch nicht bewertet.*Hoch/s);
    assert.equal(await page.locator('#ai-status').getAttribute('data-state'), 'streaming');
    assert.equal(await page.locator('#message').inputValue(), 'Laufender Entwurf');
    await page.locator('#updates button').click();
    await page.clock.runFor(3000);
    assert.equal(await page.locator('#ai-status').getAttribute('data-state'), 'completed');
    const output = await page.locator('#ai-output').textContent();
    await change(context, c, 'close');
    await page.clock.runFor(17000);
    await until(async () => (await page.locator('#case-head').getAttribute('data-closed')) === 'true');
    assert.equal(await page.locator('#message').inputValue(), 'Laufender Entwurf');
    assert.equal(await page.locator('#message').isDisabled(), true);
    assert.equal(await page.locator('#send').isDisabled(), true);
    assert.equal(await page.locator('#ai-output').textContent(), output);
});

